// Rule-conformance audit: runs every parseable Garo="English" example in
// docs/grammar_rules_structured/*.yaml through translate() and compares to
// the rule's own form. REPORT-ONLY by default (always exits 0); pass
// --enforce to fail on any rule-example mismatch not in the baseline
// (src/data/rule_conformance_baseline.json). Writes docs/RULE_CONFORMANCE_REPORT.md.
import fs from 'fs';
import path from 'path';
import yaml from 'js-yaml';
import { translate } from '../src/translationEngine.js';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const enforce = process.argv.includes('--enforce');
const N = s => String(s).toLowerCase().replace(/[·.˙?!,'’]/g, '').replace(/\s+/g, ' ').trim();

async function main() {
  const dir = path.join(ROOT, 'docs/grammar_rules_structured');
  const master = JSON.parse(fs.readFileSync(path.join(ROOT, 'master_dictionary.json'), 'utf8'));
  const layers = N(fs.readFileSync(path.join(ROOT, 'src/data/corrections.json'), 'utf8') +
                   fs.readFileSync(path.join(ROOT, 'src/data/phrase_maps.js'), 'utf8'));
  const inMaster = new Set(master.map(r => N(r.garo)));
  const rows = [];
  for (const f of fs.readdirSync(dir).filter(x => x.endsWith('.yaml')).sort()) {
    const d = yaml.load(fs.readFileSync(path.join(dir, f), 'utf8'));
    let ex = d.examples || [];
    if (!Array.isArray(ex)) ex = Object.values(ex);
    for (const e of ex) {
      const s = typeof e === 'string' ? e : (e && e.garo && e.english ? `${e.garo} = "${e.english}"` : '');
      for (const m of s.matchAll(/([^=;"“”]+?)\s*=\s*["“]([^"”]+)["”]/g)) {
        const garo = m[1].replace(/^[\s'`*]+|[\s'`*]+$/g, '').replace(/^.*?:\s*/, '');
        const en = m[2].split('/')[0].trim();
        if (!garo || garo.length > 80 || /[→(]/.test(garo)) continue;
        let out = '', meth = '', conf = 0;
        try { const o = await translate(en); out = o.garo || ''; meth = o.method; conf = o.confidence; } catch { out = 'ERR'; }
        rows.push({ rule: d.id, en, garo, out, meth, conf, match: N(out) === N(garo),
          present: inMaster.has(N(garo)) || layers.includes(N(garo)) });
      }
    }
  }
  const total = rows.length, ok = rows.filter(r => r.match).length;
  const orphan = rows.filter(r => !r.present).length;
  const base = path.join(ROOT, 'src/data/rule_conformance_baseline.json');
  const baseline = fs.existsSync(base) ? new Set(JSON.parse(fs.readFileSync(base, 'utf8'))) : new Set();
  const key = r => `${r.rule}|${r.en}|${r.garo}`;
  const newFails = rows.filter(r => !r.match && !baseline.has(key(r)));
  const md = [`# Rule conformance report`, '',
    'Auto-generated by scripts/audit-rule-conformance.mjs; do not hand-edit. Report-only unless run with --enforce.', '',
    `Examples: ${total} | runtime matches rule: ${ok} (${total ? Math.round(100 * ok / total) : 0}%) | orphan (in no entry layer): ${orphan} | mismatches not in baseline: ${newFails.length}`, '',
    '| Rule | English | Rule form | Runtime | Method | Conf |', '|---|---|---|---|---|---|',
    ...rows.filter(r => !r.match).map(r => `| ${r.rule} | ${r.en} | ${r.garo} | ${r.out} | ${r.meth} | ${r.conf} |`), ''].join('\n');
  fs.writeFileSync(path.join(ROOT, 'docs/RULE_CONFORMANCE_REPORT.md'), md);
  if (process.argv.includes('--write-baseline')) {
    fs.writeFileSync(base, JSON.stringify(rows.filter(r => !r.match).map(key), null, 1) + '\n');
  }
  console.log(`Rule conformance: ${ok}/${total} examples match (${orphan} orphan); ${newFails.length} mismatch(es) not in baseline. ${enforce ? '[ENFORCE]' : '[report-only]'}`);
  if (enforce && newFails.length) { newFails.forEach(r => console.log('  NEW', key(r), '->', r.out)); process.exit(1); }
}
main().catch(e => { console.log('Rule conformance: audit could not run (report-only, not failing):', e.message); process.exit(enforce ? 1 : 0); });
