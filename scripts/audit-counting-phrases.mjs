// Report-only audit: find "<number> <noun>" dictionary entries whose
// stored value disagrees with what garo_classifier.js's already-
// confirmed classifier-composition system would derive from the bare
// noun's own dictionary entry.
//
// IMPORTANT: this script only READS master_dictionary.json and
// garo_dictionary.json and WRITES a findings report. It never modifies
// any dictionary file. Per docs/CLAUDE_B_MIGRATION_20260809.md section
// 3.E: a prior session shipped an auto-correction based on this exact
// logic, then reverted it after finding this project's standing
// discipline requires every linguistic value to be individually
// native-confirmed, even when a derivation looks mechanically obvious.
// This script exists to make that review easy, not to skip it.
//
// Usage: node scripts/audit-counting-phrases.mjs
// Output: docs/COUNTING_PHRASE_AUDIT_20260810.md (candidate list for
// Claude A / native-speaker review, batched by classifier category)

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import {
  NUMBER_WORDS,
  CLASSIFIER_MAP,
  countNoun,
  parseCountingPhrase,
} from '../src/garo_classifier.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.join(__dirname, '..');

const files = ['garo_dictionary.json', 'master_dictionary.json'];

// Build a canonical bare-noun -> garo lookup the same way prepare-data.js's
// finalized dict effectively does: prefer the LAST non-empty, non-
// SUPERSEDED entry for a given lowercased english key across both files,
// scanning master_dictionary.json second so it wins ties (mirrors
// prepare-data.js's own master-preference intent for this purpose).
export function isSuperseded(item) {
  return typeof item.notes === 'string' && /^superseded\b/i.test(item.notes);
}

// Pure merge logic, injectable for testing without touching disk. `sources`
// is an array of {name, items} processed in order; later sources win ties
// for a given lowercased english key. Production usage scans
// garo_dictionary.json first, master_dictionary.json second, so master
// wins ties (mirrors prepare-data.js's own master-preference intent).
export function mergeBareNounIndex(sources) {
  const index = {};
  for (const { items } of sources) {
    for (const item of items) {
      const eng = (item.english || '').trim().toLowerCase();
      if (!eng || !item.garo) continue;
      if (isSuperseded(item)) continue;
      index[eng] = item.garo;
    }
  }
  return index;
}

function buildBareNounIndex() {
  const sources = files.map((f) => ({
    name: f,
    items: JSON.parse(fs.readFileSync(path.join(repoRoot, f), 'utf8')),
  }));
  return mergeBareNounIndex(sources);
}

function main() {
  const bareNounIndex = buildBareNounIndex();
  const mismatches = [];
  const noMapping = new Set();
  const noBareNoun = new Set();
  let checked = 0;

  for (const f of files) {
    const arr = JSON.parse(fs.readFileSync(path.join(repoRoot, f), 'utf8'));
    for (const item of arr) {
      const engRaw = (item.english || '').trim();
      const eng = engRaw.toLowerCase();
      if (!eng || !item.garo) continue;
      if (isSuperseded(item)) continue;
      const words = eng.split(/\s+/);
      if (words.length < 2 || NUMBER_WORDS[words[0]] === undefined) continue;
      const countPhrase = parseCountingPhrase(eng);
      if (!countPhrase) continue;
      checked++;

      if (!Object.prototype.hasOwnProperty.call(CLASSIFIER_MAP, countPhrase.englishNoun)) {
        noMapping.add(countPhrase.englishNoun);
        continue;
      }
      const nounGaro = bareNounIndex[countPhrase.englishNoun] || bareNounIndex[countPhrase.originalNoun];
      if (!nounGaro) {
        noBareNoun.add(countPhrase.englishNoun);
        continue;
      }
      const expected = countNoun(nounGaro, countPhrase.count, countPhrase.englishNoun);
      if (expected && item.garo !== expected) {
        mismatches.push({
          file: f,
          english: engRaw,
          stored: item.garo,
          expected,
          classifier: CLASSIFIER_MAP[countPhrase.englishNoun],
          count: countPhrase.count,
          noun: countPhrase.englishNoun,
        });
      }
    }
  }

  // Dedupe: same english phrase can appear in both files with the same
  // mismatch; report each distinct (english, stored, expected) once.
  const seen = new Set();
  const deduped = [];
  for (const m of mismatches) {
    const key = `${m.english}|${m.stored}|${m.expected}`;
    if (seen.has(key)) continue;
    seen.add(key);
    deduped.push(m);
  }

  // Group by classifier for a review-friendly report.
  const byClassifier = {};
  for (const m of deduped) {
    (byClassifier[m.classifier] ||= []).push(m);
  }

  const lines = [];
  lines.push('# Counting-Phrase Classifier Audit — 2026-08-10');
  lines.push('');
  lines.push('**Report only — no dictionary files were modified by this script or this doc.**');
  lines.push('');
  lines.push('Generated by `scripts/audit-counting-phrases.mjs`. Re-runnable any time; only');
  lines.push('reads `master_dictionary.json`/`garo_dictionary.json`, never writes to them.');
  lines.push('');
  lines.push('## Why this exists');
  lines.push('');
  lines.push('Per `docs/CLAUDE_B_MIGRATION_20260809.md` §3.E: a prior session found 413');
  lines.push('`"<number> <noun>"` entries disagreeing with `garo_classifier.js`\'s already-');
  lines.push('confirmed classifier-composition system, initially auto-corrected all of them,');
  lines.push('then reverted after finding Claude A/Thangseng had deliberately confirmed only');
  lines.push('the 3 dog-count keys and left the rest — including the structurally-identical');
  lines.push('`"three cat"` — untouched pending individual native confirmation. This report');
  lines.push('re-runs that same audit as a read-only tool, so the remaining candidates are a');
  lines.push('concrete, reviewable list rather than a one-time finding that could go stale.');
  lines.push('');
  lines.push('**Every value below is a mechanically-derived candidate, not a confirmed');
  lines.push('correction.** Some may be genuinely wrong (transcription/OCR errors, the same');
  lines.push('shape as the dog case); others may be legitimate exceptions where this noun');
  lines.push('genuinely doesn\'t follow the regular count-word pattern (irregular counting,');
  lines.push('idiom, dialect) — that distinction is exactly what needs native review, and is');
  lines.push('why this stays a report, not a script that writes to the dictionaries.');
  lines.push('');
  lines.push(`## Summary`);
  lines.push('');
  lines.push(`- \`"<number> <noun>"\` entries checked: ${checked}`);
  lines.push(`- Mismatches found (candidates for review): ${deduped.length}`);
  lines.push(`- Nouns with no explicit \`CLASSIFIER_MAP\` entry (skipped — not guessed at): ${noMapping.size}`);
  lines.push(`- Nouns with a classifier mapping but no bare dictionary entry to derive from (skipped): ${noBareNoun.size}`);
  lines.push('');
  lines.push('## Candidates by classifier category');
  lines.push('');

  const classifierOrder = Object.keys(byClassifier).sort((a, b) => byClassifier[b].length - byClassifier[a].length);
  for (const cls of classifierOrder) {
    const items = byClassifier[cls].sort((a, b) => a.english.localeCompare(b.english));
    lines.push(`### \`${cls}\` classifier (${items.length} candidates)`);
    lines.push('');
    lines.push('| English | Stored | Classifier-derived candidate | Source file |');
    lines.push('|---|---|---|---|');
    for (const m of items) {
      lines.push(`| ${m.english} | \`${m.stored}\` | \`${m.expected}\` | ${m.file} |`);
    }
    lines.push('');
  }

  if (noMapping.size) {
    lines.push('## Nouns with no `CLASSIFIER_MAP` entry (not audited, not guessed at)');
    lines.push('');
    lines.push('These nouns appear in `"<number> <noun>"` phrases but have no entry in');
    lines.push('`garo_classifier.js`\'s `CLASSIFIER_MAP` at all, so no candidate could be');
    lines.push('mechanically derived. Whether any of these should be added to the classifier');
    lines.push('system (and which classifier they\'d take) is itself a linguistic call.');
    lines.push('');
    lines.push([...noMapping].sort().map(n => `\`${n}\``).join(', '));
    lines.push('');
  }

  const outPath = path.join(repoRoot, 'docs', 'COUNTING_PHRASE_AUDIT_20260810.md');
  fs.writeFileSync(outPath, lines.join('\n') + '\n');
  console.log(`Checked ${checked} "<number> <noun>" entries.`);
  console.log(`Found ${deduped.length} mismatches across ${classifierOrder.length} classifier categories.`);
  console.log(`${noMapping.size} nouns skipped (no CLASSIFIER_MAP entry).`);
  console.log(`Report written to ${path.relative(repoRoot, outPath)}`);
}

// Only run when executed directly (`node scripts/audit-counting-phrases.mjs`),
// not when imported — lets tests import mergeBareNounIndex/isSuperseded
// without triggering the full file-scan + report-write side effects.
if (import.meta.url === `file://${process.argv[1]}`) {
  main();
}
