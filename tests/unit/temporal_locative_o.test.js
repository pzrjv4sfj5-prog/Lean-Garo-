import test from 'node:test';
import assert from 'node:assert/strict';
import { translate } from '../../src/translationEngine.js';

// 2026-10-20 (Claude B). PO ruling (2026-10-20, relayed in session; builds on
// docs/HANDOFF_CLAUDE_B_20261019_temporal_locative.md, RULE-053, NV-171/174):
// a time word in an EVENT sentence takes locative -o (da·alo, mijalo, knalo;
// "now" = da·o already ends in -o), NEVER object -ko, and the real object
// (mi) keeps its own -ko. Isolated forms: today = Da·al, yesterday = Mijal,
// tomorrow = Knal. Destinations default to the -chi form (bajalchi).
// Pre-fix: "i eat rice today" -> "Anga da·alo·ko Cha·a" (rice dropped).
// Evidence class: PO-pasted rule, no native attribution (see handoff).
// Comparison ignores case and raka/apostrophe punctuation (cosmetic verb
// capitalization is a separate known item).
const norm = (s) => String(s).toLowerCase().replace(/[^\p{L} ]/gu, '').replace(/\s+/g, ' ').trim();

const EVENT = [
  ['i eat rice today', 'Da·alo anga miko cha·a'],
  ['dogs eat rice today', 'Da·alo achakrang miko cha·a'],
  ['two dogs eat rice today', 'Da·alo achak manggni miko cha·a'],
  ['i went to the market yesterday', 'Mijalo anga bajalchi re·anga'],
  ['i eat rice tomorrow', 'Knalo anga miko cha·a'],
  ['i eat rice now', 'Da·o anga miko cha·a'],
];
for (const [eng, garo] of EVENT) {
  test(`time word takes -o, object keeps -ko: ${eng}`, async () => {
    const r = await translate(eng);
    assert.equal(norm(r.garo), norm(garo));
  });
}

test('no time word ever takes object -ko', async () => {
  for (const eng of ['i eat rice today', 'i eat rice yesterday', 'i eat rice tomorrow', 'i eat rice now', 'dogs eat rice today', 'two dogs eat rice today']) {
    const r = await translate(eng);
    assert.ok(!/(da.?alo|mi.?jalo?|mejalo?|knalo?|da.?o)\s*.?ko\b/i.test(String(r.garo).normalize()), `${eng} -> ${r.garo}`);
    assert.ok(/mi.?ko/i.test(r.garo), `object mi-ko must survive: ${r.garo}`);
  }
});

test('isolated forms are the base (no -o)', async () => {
  assert.equal(norm((await translate('today')).garo), norm('Da·al'));
  assert.equal(norm((await translate('yesterday')).garo), 'mijal');
  assert.equal(norm((await translate('tomorrow')).garo), 'knal');
});

test('-de is never generated by default', async () => {
  for (const eng of ['i eat rice today', 'i went to the market yesterday']) {
    const r = await translate(eng);
    assert.ok(!/(alde|jalde)\b/i.test(norm(r.garo)), r.garo);
  }
});
